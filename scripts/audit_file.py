# HTML
# ---------------------------------------------------------------------------

def parse_html(text: str) -> list[Finding]:
    findings: list[Finding] = []
    for m in re.finditer(r"<meta\b[^>]*>", text, re.I):
        attrs = {k.lower(): v for k, v in re.findall(
            r"([\w:-]+)\s*=\s*[\"']([^\"']*)[\"']", m.group())}
        if attrs.get("name", "").lower() != "generator":
            continue
        content = attrs.get("content", "")
        markers = find_ai_markers(content)
        if markers:
            findings.append(Finding(
                severity="medium", confidence="confirmed",
                category="ai-metadata", location="<meta name=\"generator\">",
                evidence=f"generator={content}",
                note=f"AI-generator marker(s): {', '.join(markers)}",
            ))
        elif any(cms in content.lower() for cms in CMS_GENERATORS):
            findings.append(Finding(
                severity="informational", confidence="confirmed",
                category="generator-meta", location="<meta name=\"generator\">",
                evidence=f"generator={content}", note=CMS_GENERATOR_NOTE,
            ))
        elif content.strip():
            findings.append(Finding(
                severity="informational", confidence="confirmed",
                category="generator-meta", location="<meta name=\"generator\">",
                evidence=f"generator={content}",
                note="generator tag present; not a known CMS, no AI markers",
            ))
    for m in re.finditer(r"\s(data-ai[\w-]*)\s*=\s*[\"']([^\"']*)[\"']",
                         text, re.I):
        findings.append(Finding(
            severity="medium", confidence="confirmed", category="ai-metadata",
            location=f"attribute {m.group(1)}",
            evidence=f"{m.group(1)}={m.group(2)}",
            note="data-ai* attribute present in markup",
        ))
    _scan_jsonld_blocks(text, "JSON-LD script block", findings)
    return findings


# ---------------------------------------------------------------------------
# Markdown (YAML frontmatter only, line-based — no yaml lib)
# ---------------------------------------------------------------------------

_FRONTMATTER_KEY_RE = re.compile(
    r"^(generator|model|ai[-_].*|claude.*|gpt.*|llm.*)$", re.I)


def parse_markdown(text: str) -> list[Finding]:
    findings: list[Finding] = []
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return findings
    end = None
    for i in range(1, len(lines)):
        if lines[i].strip() == "---":
            end = i
            break
    if end is None:
        return findings
    for i in range(1, end):
        m = re.match(r"^([A-Za-z0-9_.-]+)\s*:\s*(.*)$", lines[i])
        if not m:
            continue
        key, value = m.group(1), m.group(2).strip().strip("\"'")
        markers = find_ai_markers(value)
        if _FRONTMATTER_KEY_RE.match(key) or markers:
            findings.append(Finding(
                severity="medium", confidence="confirmed",
                category="ai-metadata",
                location=f"frontmatter line {i + 1}",
                evidence=f"{key}: {value}",
                note=("AI-related frontmatter key"
                      if _FRONTMATTER_KEY_RE.match(key) else
                      f"AI-generator marker(s) in value: {', '.join(markers)}"),
            ))
    return findings


# ---------------------------------------------------------------------------
# Layer C: c2patool enrichment (optional, only when on PATH)
# ---------------------------------------------------------------------------

def enrich_c2pa(path: str, report: Report) -> None:
    """Cross-check c2pa-manifest findings with c2patool when available.

    Never treats c2patool errors as presence: nonzero exit or "No claim
    found" / "No JUMBF data found" output means the manifest is ABSENT;
    chunk-scan findings are then removed and the discrepancy noted.
    """
    c2pa_findings = [f for f in report.findings if f.category == "c2pa-manifest"]
    if not c2pa_findings:
        return
    tool = shutil.which("c2patool")
    if not tool:
        report.add_note(C2PATOOL_ABSENT_NOTE)
        return
    try:
        proc = subprocess.run([tool, path], capture_output=True, text=True,
                              timeout=30)
    except (OSError, subprocess.TimeoutExpired) as e:
        report.add_note(f"c2patool could not be run ({e}); manifest "
                        "findings are chunk-scan only and unverified.")
        return
    combined = (proc.stdout or "") + "\n" + (proc.stderr or "")
    if proc.returncode != 0 or "No claim found" in combined \
            or "No JUMBF data found" in combined:
        report.findings = [f for f in report.findings
                           if f.category != "c2pa-manifest"]
        report.add_note(
            "chunk scan indicated C2PA data, but c2patool reported no "
            "claim; c2pa-manifest findings removed as a likely stale or "
            "malformed chunk.")
        return
    try:
        manifest = json.loads(proc.stdout)
    except (json.JSONDecodeError, TypeError):
        report.add_note("c2patool output was not parseable JSON; manifest "
                        "findings are chunk-scan only.")
        return
    manifests = manifest.get("manifests", {})
    active = manifests.get(manifest.get("active_manifest"), {}) \
        if isinstance(manifests, dict) else {}
    gen = active.get("claim_generator", "")
    assertions = [a.get("label", "?")
                  for a in active.get("assertions", [])
                  if isinstance(a, dict)]
    sig = active.get("signature_info", {})
    signer = sig.get("issuer", "") or sig.get("common_name", "")
    for f in c2pa_findings:
        detail = []
        if gen:
            detail.append(f"claim_generator={gen}")
        if assertions:
            detail.append(f"assertions: {', '.join(assertions)}")
        if signer:
            detail.append(f"signed by: {signer}")
        if detail:
            f.note += ". c2patool: " + "; ".join(detail)


