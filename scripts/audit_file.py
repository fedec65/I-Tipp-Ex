def find_ai_markers(text: str) -> list[str]:
    low = text.lower()
    return [m for m in AI_MARKERS if m in low]


def check_metadata_value(field: str, value: str, location: str,
                         findings: list[Finding],
                         informational_otherwise: bool = True) -> None:
    """Append a finding if value carries AI markers; optionally informational."""
    markers = find_ai_markers(value)
    short = value if len(value) <= 160 else value[:157] + "..."
    if markers:
        findings.append(Finding(
            severity="medium", confidence="confirmed", category="ai-metadata",
            location=location,
            evidence=f"{field}={short}",
            note=f"AI-generator marker(s): {', '.join(markers)}",
        ))
    elif informational_otherwise and value.strip():
        findings.append(Finding(
            severity="informational", confidence="confirmed",
            category="generator-meta",
            location=location,
            evidence=f"{field}={short}",
            note="metadata field present; no AI-generator markers found",
        ))


def _xmp_scan(packet: str, location: str, findings: list[Finding]) -> None:
    """Scan an XMP packet for CreatorTool, c2pa namespace, AI markers."""
    if "c2pa:" in packet or "ns.adobe.com/c2pa" in packet:
        findings.append(Finding(
            severity="medium", confidence="confirmed", category="c2pa-manifest",
            location=location,
            evidence="XMP packet references the c2pa: namespace",
            note="C2PA metadata present in XMP",
        ))
    m = re.search(r"xmp:CreatorTool[\"'>\s]*=?[\"'>]?\s*([^<\"']+)", packet)
    if m:
        check_metadata_value("xmp:CreatorTool", m.group(1).strip(),
                             location, findings)
    markers = find_ai_markers(packet)
    if markers:
        findings.append(Finding(
            severity="medium", confidence="confirmed", category="ai-metadata",
            location=location,
            evidence="XMP packet contains AI-generator marker(s)",
            context=packet[:160],
            note=f"AI-generator marker(s): {', '.join(markers)}",
        ))


def _c2pa_finding(location: str, evidence: str) -> Finding:
    return Finding(
        severity="medium", confidence="confirmed", category="c2pa-manifest",
        location=location, evidence=evidence,
        note="content-credential manifest chunk present in container",
    )


