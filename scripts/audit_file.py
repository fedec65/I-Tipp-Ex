_TEXTUAL = {"text", "markdown", "html", "svg"}


def audit_file(path: str, max_bytes: int = DEFAULT_MAX_BYTES) -> Report:
    """Audit one file; never modifies it. Returns a Report."""
    report = Report(target=path)
    with open(path, "rb") as fh:
        raw = fh.read(max(0, max_bytes) + 1)
    if len(raw) > max_bytes:
        raw = raw[:max_bytes]
        report.add_note(f"Input truncated at {max_bytes} bytes "
                        "(--max-bytes); findings cover only that prefix.")

    container = detect_container(raw)
    findings: list[Finding] = []
    text_scanned = False

    if container == "png":
        findings = parse_png(raw)
    elif container == "jpeg":
        findings = parse_jpeg(raw)
    elif container == "webp":
        findings = parse_webp(raw)
    elif container == "gif":
        findings = parse_gif(raw)
    elif container == "tiff":
        _tiff_ascii_fields(raw, "TIFF IFD0", findings)
    elif container == "pdf":
        findings = parse_pdf(raw)
    elif container == "docx":
        try:
            findings = parse_docx(raw)
        except (zipfile.BadZipFile, OSError) as e:
            report.add_note(f"could not open DOCX zip: {e}")
    elif container == "odt":
        try:
            findings = parse_odt(raw)
        except (zipfile.BadZipFile, OSError) as e:
            report.add_note(f"could not open ODT zip: {e}")
    elif container == "epub":
        try:
            findings = parse_epub(raw)
        except (zipfile.BadZipFile, OSError) as e:
            report.add_note(f"could not open EPUB zip: {e}")
    elif container in _TEXTUAL:
        text = raw.decode("utf-8", "replace")
        if container == "svg":
            findings = parse_svg(text)
        elif container == "html":
            findings = parse_html(text)
        elif container == "markdown":
            findings = parse_markdown(text)
        findings.extend(audit_text.scan_text(text))
        text_scanned = True
    else:  # unknown-binary
        report.add_note(
            "unrecognized binary format, no metadata scan performed")

    for f in findings:
        report.add_finding(f)

    if any(f.category == "c2pa-manifest" for f in report.findings):
        enrich_c2pa(path, report)
    if text_scanned:
        report.add_note(STATISTICAL_WATERMARK_NOTE)
    return report


def main(argv=None) -> int:
    parser = build_base_parser(
        description="i-tipp-ex Layers B+C: container metadata audit "
                    "(C2PA, EXIF/XMP, generator markers). Read-only, offline."
    )
    parser.add_argument("file", help="file to audit (routed by magic bytes)")
    args = parser.parse_args(argv)
    report = audit_file(args.file, max_bytes=args.max_bytes)
    emit_report(report, args)
    return 0


if __name__ == "__main__":
    sys.exit(main())
