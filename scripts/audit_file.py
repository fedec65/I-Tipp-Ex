# JPEG
# ---------------------------------------------------------------------------

def parse_jpeg(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    pos = 2  # after SOI
    while pos + 4 <= len(data):
        if data[pos] != 0xFF:
            pos += 1
            continue
        marker = data[pos + 1]
        if marker == 0xDA:  # SOS: image data begins
            break
        if marker in (0xD8, 0xD9) or 0xD0 <= marker <= 0xD7 or marker == 0x01:
            pos += 2
            continue
        length = int.from_bytes(data[pos + 2:pos + 4], "big")
        if length < 2:
            break
        seg = data[pos + 4:pos + 2 + length]
        loc = f"JPEG APP{marker - 0xE0}" if 0xE0 <= marker <= 0xEF else \
            f"JPEG marker 0xFF{marker:02X}"
        if marker == 0xE1:  # APP1
            if seg.startswith(b"Exif\x00\x00"):
                _tiff_ascii_fields(seg[6:], f"{loc} EXIF", findings)
            elif seg.startswith(b"http://ns.adobe.com/xap/1.0/\x00"):
                _xmp_scan(seg[29:].decode("utf-8", "replace"),
                          f"{loc} XMP", findings)
        elif marker == 0xEB:  # APP11
            if seg[:2] == b"JP":
                findings.append(_c2pa_finding(
                    loc, "APP11 JUMBF box (JP header) — C2PA manifest store"))
        elif marker == 0xFE:  # COM
            check_metadata_value("COM", seg.decode("utf-8", "replace"),
                                 "JPEG COM segment", findings)
        pos += 2 + length
    return findings


# ---------------------------------------------------------------------------
# WebP
# ---------------------------------------------------------------------------

def parse_webp(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    pos = 12
    while pos + 8 <= len(data):
        fourcc = data[pos:pos + 4]
        size = int.from_bytes(data[pos + 4:pos + 8], "little")
        payload = data[pos + 8:pos + 8 + size]
        loc = f"WebP chunk {fourcc.decode('latin-1', 'replace')!r}"
        if fourcc == b"C2PA":
            findings.append(_c2pa_finding(loc, f"C2PA chunk ({size} bytes)"))
        elif fourcc == b"XMP ":
            _xmp_scan(payload.decode("utf-8", "replace"), loc, findings)
        elif fourcc == b"EXIF":
            _tiff_ascii_fields(payload, loc, findings)
        pos += 8 + size + (size & 1)
    return findings


