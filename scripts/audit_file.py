def _xml_texts(xml_bytes: bytes, wanted: set[str]) -> list[tuple[str, str]]:
    """Return (local_tag, text) pairs for elements whose local name is wanted."""
    out = []
    try:
        root = ET.fromstring(xml_bytes)
    except ET.ParseError:
        return out
    for elem in root.iter():
        if _local(elem.tag) in wanted and elem.text and elem.text.strip():
            out.append((_local(elem.tag), elem.text.strip()))
    return out


def parse_docx(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    zf = zipfile.ZipFile(io.BytesIO(data))
    names = set(zf.namelist())

    if "docProps/core.xml" in names:
        for tag, text in _xml_texts(zf.read("docProps/core.xml"),
                                    {"creator", "lastmodifiedby"}):
            check_metadata_value(f"core.xml {tag}", text,
                                 "docProps/core.xml", findings)
    if "docProps/app.xml" in names:
        for tag, text in _xml_texts(zf.read("docProps/app.xml"),
                                    {"application", "appversion", "company"}):
            if tag == "application":
                markers = find_ai_markers(text)
                if markers:
                    findings.append(Finding(
                        severity="medium", confidence="confirmed",
                        category="ai-metadata",
                        location="docProps/app.xml",
                        evidence=f"Application={text}",
                        note=f"AI-generator marker(s): {', '.join(markers)}",
                    ))
                else:
                    findings.append(Finding(
                        severity="informational", confidence="confirmed",
                        category="generator-meta",
                        location="docProps/app.xml",
                        evidence=f"Application={text}",
                        note="authoring application; no AI-generator markers",
                    ))
            else:
                check_metadata_value(f"app.xml {tag}", text,
                                     "docProps/app.xml", findings)
    if "docProps/custom.xml" in names:
        try:
            root = ET.fromstring(zf.read("docProps/custom.xml"))
            for prop in root:
                name = prop.attrib.get("name", "?")
                for child in prop:
                    if child.text:
                        check_metadata_value(f"custom property {name!r}",
                                             child.text.strip(),
                                             "docProps/custom.xml", findings)
        except ET.ParseError:
            pass
    for name in sorted(names):
        if name.startswith("customXml/") and name.endswith(".xml"):
            for tag, text in _xml_texts(zf.read(name),
                                        {"creator", "generator", "tool"}):
                check_metadata_value(f"{name} {tag}", text, name, findings)
    return findings


def parse_odt(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    zf = zipfile.ZipFile(io.BytesIO(data))
    if "meta.xml" not in zf.namelist():
        return findings
    wanted = {"generator", "initial-creator", "creator", "creation-date"}
    for tag, text in _xml_texts(zf.read("meta.xml"), wanted):
        markers = find_ai_markers(text)
        if markers:
            findings.append(Finding(
                severity="medium", confidence="confirmed",
                category="ai-metadata", location=f"meta.xml {tag}",
                evidence=f"{tag}={text}",
                note=f"AI-generator marker(s): {', '.join(markers)}",
            ))
        else:
            findings.append(Finding(
                severity="informational", confidence="confirmed",
                category="generator-meta", location=f"meta.xml {tag}",
                evidence=f"{tag}={text}",
                note="ODF metadata field; no AI-generator markers",
            ))
    return findings


_JSONLD_RE = re.compile(
    r"<script[^>]*type=[\"']application/ld\+json[\"'][^>]*>(.*?)</script>",
    re.I | re.S)


def _scan_jsonld_blocks(text: str, location: str,
                        findings: list[Finding]) -> None:
    for m in _JSONLD_RE.finditer(text):
        markers = find_ai_markers(m.group(1))
        if markers:
            findings.append(Finding(
                severity="medium", confidence="confirmed",
                category="ai-metadata", location=location,
                evidence="JSON-LD block contains AI-generator marker(s)",
                context=m.group(1).strip()[:160],
                note=f"AI-generator marker(s): {', '.join(markers)}",
            ))


def parse_epub(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    zf = zipfile.ZipFile(io.BytesIO(data))
    for name in sorted(zf.namelist()):
        low = name.lower()
        if low.endswith(".opf"):
            for tag, text in _xml_texts(zf.read(name),
                                        {"creator", "generator", "meta"}):
                check_metadata_value(f"{name} {tag}", text, name, findings)
        elif low.endswith((".xhtml", ".html", ".htm")):
            text = zf.read(name).decode("utf-8", "replace")
            for m in re.finditer(r"<meta\b[^>]*>", text, re.I):
                attrs = dict(re.findall(
                    r"([\w:-]+)\s*=\s*[\"']([^\"']*)[\"']", m.group()))
                if attrs.get("name", "").lower() == "generator":
                    check_metadata_value("meta generator",
                                         attrs.get("content", ""),
                                         f"{name} <meta generator>", findings)
            _scan_jsonld_blocks(text, f"{name} JSON-LD", findings)
    return findings


