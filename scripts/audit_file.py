_PDF_FIELD_RE = re.compile(
    rb"/(Producer|Creator|Title|Author|CreationDate)\s*\(((?:[^()\\]|\\.)*)\)")

_PDF_ESCAPES = {b"\\n": "\n", b"\\r": "\r", b"\\t": "\t",
                b"\\(": "(", b"\\)": ")", b"\\\\": "\\"}


def _pdf_unescape(raw: bytes) -> str:
    s = raw
    for k, v in _PDF_ESCAPES.items():
        s = s.replace(k, v.encode("latin-1"))
    return s.decode("latin-1", "replace")


def _flate_stream_spans(data: bytes) -> list[tuple[int, int]]:
    """Spans of stream...endstream regions that follow a /FlateDecode filter."""
    spans = []
    for m in re.finditer(rb"\bstream\r?\n", data):
        if data[max(0, m.start() - 3):m.start()] == b"end":
            continue  # this is the 'stream' inside 'endstream'
        e = data.find(b"endstream", m.end())
        if e == -1:
            continue
        prefix = data[max(0, m.start() - 1024):m.start()]
        if b"/FlateDecode" in prefix:
            spans.append((m.start(), e + len(b"endstream")))
    return spans


def parse_pdf(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    for m in _PDF_FIELD_RE.finditer(data):
        field = m.group(1).decode()
        value = _pdf_unescape(m.group(2)).strip()
        if value:
            check_metadata_value(f"/{field}", value,
                                 f"PDF /Info /{field}", findings)

    xs = data.find(b"<?xpacket")
    if xs != -1:
        xe = data.find(b"<?xpacket end", xs)
        packet = data[xs: xe if xe != -1 else xs + 65536]
        _xmp_scan(packet.decode("utf-8", "replace"),
                  "PDF XMP metadata stream", findings)

    # Whole-file marker scan, excluding FlateDecode stream payloads.
    spans = _flate_stream_spans(data)
    excluded = bytearray(data)
    for s0, s1 in spans:
        excluded[s0:s1] = b"\x00" * (s1 - s0)
    markers = find_ai_markers(bytes(excluded).decode("latin-1", "replace"))
    already = {f.evidence for f in findings}
    if markers and not any(all(mk in ev.lower() for mk in markers)
                           for ev in already):
        findings.append(Finding(
            severity="medium", confidence="confirmed", category="ai-metadata",
            location="PDF (outside compressed streams)",
            evidence="AI-generator marker bytes present",
            note=f"AI-generator marker(s): {', '.join(markers)}; "
                 "compressed /FlateDecode stream payloads were excluded "
                 "from this scan",
        ))
    if data.count(b"%%EOF") > 1 and markers:
        findings[-1].note += ". " + INCREMENTAL_EDIT_NOTE + "."
    return findings


