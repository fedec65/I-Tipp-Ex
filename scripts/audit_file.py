def _png_text_value(keyword: str, value: str, location: str,
                    findings: list[Finding]) -> None:
    kw = keyword.lower()
    if kw in ("parameters", "prompt") and any(
            m in value.lower() for m in PROMPT_FIELD_MARKERS):
        short = value if len(value) <= 200 else value[:197] + "..."
        findings.append(Finding(
            severity="medium", confidence="confirmed", category="generator-meta",
            location=location,
            evidence=f"{keyword}={short}",
            note="prompt/generation-parameter metadata typical of image "
                 "generators (e.g. AUTOMATIC1111-style PNG info)",
        ))
        return
    if kw == "xml:com.adobe.xmp":
        _xmp_scan(value, location, findings)
        return
    if kw in ("software", "comment", "parameters", "prompt", "title",
              "description", "author"):
        check_metadata_value(keyword, value, location, findings)


def parse_png(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    pos = 8  # after signature
    idx = 0
    while pos + 8 <= len(data):
        length = int.from_bytes(data[pos:pos + 4], "big")
        ctype = data[pos + 4:pos + 8]
        cdata = data[pos + 8:pos + 8 + length]
        if len(cdata) < length:
            break
        loc = f"PNG chunk {ctype.decode('latin-1', 'replace')!r} (#{idx})"
        idx += 1
        if ctype == b"caBX" or ctype.lower() == b"c2pa":
            findings.append(_c2pa_finding(loc, f"{ctype.decode('latin-1')} chunk "
                                               f"({length} bytes)"))
        elif ctype == b"tEXt":
            keyword, _, value = cdata.partition(b"\x00")
            _png_text_value(keyword.decode("latin-1", "replace"),
                            value.decode("latin-1", "replace"), loc, findings)
        elif ctype == b"zTXt":
            keyword, _, rest = cdata.partition(b"\x00")
            try:
                value = zlib.decompress(rest[1:]).decode("utf-8", "replace")
                _png_text_value(keyword.decode("latin-1", "replace"),
                                value, loc, findings)
            except (zlib.error, IndexError):
                pass
        elif ctype == b"iTXt":
            try:
                kw_end = cdata.index(b"\x00")
                keyword = cdata[:kw_end].decode("utf-8", "replace")
                rest = cdata[kw_end + 1:]
                flag, rest = rest[0], rest[2:]
                lang_end = rest.index(b"\x00")
                rest = rest[lang_end + 1:]
                tr_end = rest.index(b"\x00")
                value = rest[tr_end + 1:]
                if flag == 1:
                    value = zlib.decompress(value)
                _png_text_value(keyword, value.decode("utf-8", "replace"),
                                loc, findings)
            except (ValueError, IndexError, zlib.error):
                pass
        pos += 8 + length + 4  # skip CRC
        if ctype == b"IEND":
            break
    return findings


# ---------------------------------------------------------------------------
# Minimal TIFF / EXIF IFD0 reader (classic + BigTIFF)
# ---------------------------------------------------------------------------

def _tiff_ascii_fields(tiff: bytes, location: str,
                       findings: list[Finding]) -> None:
    if len(tiff) < 8:
        return
    bo = tiff[:2]
    if bo == b"II":
        endian = "little"
    elif bo == b"MM":
        endian = "big"
    else:
        return
    magic = int.from_bytes(tiff[2:4], endian)
    bigtiff = magic == 43
    if not bigtiff and magic != 42:
        return

    def u16(b: bytes) -> int:
        return int.from_bytes(b, endian)

    if bigtiff:
        ifd_off = int.from_bytes(tiff[8:16], endian)
        entry_size, count_len = 20, 8
    else:
        ifd_off = int.from_bytes(tiff[4:8], endian)
        entry_size, count_len = 12, 4
    if ifd_off >= len(tiff):
        return
    if bigtiff:
        n = int.from_bytes(tiff[ifd_off:ifd_off + 8], endian)
        entries_at = ifd_off + 8
    else:
        n = u16(tiff[ifd_off:ifd_off + 2])
        entries_at = ifd_off + 2

    TAG_NAMES = {0x010F: "Make", 0x0110: "Model", 0x0131: "Software",
                 0x010E: "ImageDescription", 0x02BC: "XMP"}
    for i in range(min(n, 512)):
        off = entries_at + i * entry_size
        if off + entry_size > len(tiff):
            break
        tag = u16(tiff[off:off + 2])
        typ = u16(tiff[off + 2:off + 4])
        count = int.from_bytes(tiff[off + 4:off + 4 + count_len], endian)
        inline = 8 if bigtiff else 4
        if count > 65536:
            continue
        if count <= inline:
            raw = tiff[off + 4 + count_len: off + 4 + count_len + count]
        else:
            voff = int.from_bytes(
                tiff[off + 4 + count_len: off + 4 + count_len + inline], endian)
            raw = tiff[voff:voff + count]
        name = TAG_NAMES.get(tag)
        if name is None or not raw:
            continue
        if name == "XMP":
            _xmp_scan(raw.decode("utf-8", "replace"),
                      f"{location} tag 0x02BC", findings)
            continue
        if typ not in (1, 2, 7):
            continue
        value = raw.split(b"\x00")[0].decode("utf-8", "replace").strip()
        if value:
            check_metadata_value(name, value, f"{location} {name}", findings)


