def _gif_subblocks(data: bytes, pos: int) -> tuple[bytes, int]:
    out = bytearray()
    while pos < len(data):
        n = data[pos]
        pos += 1
        if n == 0:
            break
        out += data[pos:pos + n]
        pos += n
    return bytes(out), pos


def parse_gif(data: bytes) -> list[Finding]:
    findings: list[Finding] = []
    if len(data) < 13:
        return findings
    pos = 6  # header
    packed = data[10]
    pos = 13
    if packed & 0x80:  # global color table
        pos += 3 * (2 ** ((packed & 0x07) + 1))
    while pos < len(data):
        b = data[pos]
        if b == 0x3B:  # trailer
            break
        if b == 0x2C:  # image descriptor
            packed = data[pos + 9] if pos + 9 < len(data) else 0
            pos += 10
            if packed & 0x80:
                pos += 3 * (2 ** ((packed & 0x07) + 1))
            pos += 1  # LZW min code size
            _, pos = _gif_subblocks(data, pos)
            continue
        if b == 0x21 and pos + 1 < len(data):
            label = data[pos + 1]
            if label == 0xFE:  # comment extension
                payload, pos = _gif_subblocks(data, pos + 2)
                check_metadata_value(
                    "GIF comment", payload.decode("utf-8", "replace"),
                    "GIF comment extension", findings)
                continue
            if label == 0xFF:  # application extension
                app_id = data[pos + 2:pos + 13]
                payload, pos = _gif_subblocks(data, pos + 14)
                if b"XMP" in app_id:
                    _xmp_scan(payload.decode("utf-8", "replace"),
                              "GIF application extension (XMP)", findings)
                else:
                    markers = find_ai_markers(payload.decode("utf-8", "replace"))
                    if markers:
                        findings.append(Finding(
                            severity="medium", confidence="confirmed",
                            category="ai-metadata",
                            location="GIF application extension",
                            evidence=f"application {app_id.decode('latin-1', 'replace')!r} "
                                     "data contains AI-generator marker(s)",
                            note=f"AI-generator marker(s): {', '.join(markers)}",
                        ))
                continue
            pos += 2
            _, pos = _gif_subblocks(data, pos)
            continue
        pos += 1
    return findings


