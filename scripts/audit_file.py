def _local(tag: str) -> str:
    return tag.rsplit("}", 1)[-1].lower()


def parse_svg(text: str) -> list[Finding]:
    findings: list[Finding] = []
    try:
        root = ET.fromstring(text)
    except ET.ParseError as e:
        findings.append(Finding(
            severity="informational", confidence="informational",
            category="generator-meta", location="SVG document",
            evidence=f"SVG XML parse failed: {e}",
            note="metadata scan skipped for malformed SVG",
        ))
        return findings
    for key in root.attrib:
        ns = key.lower()
        if "inkscape" in ns or "sodipodi" in ns:
            findings.append(Finding(
                severity="informational", confidence="confirmed",
                category="generator-meta", location="SVG root attributes",
                evidence=f"namespace attribute {key}",
                note="Inkscape/sodipodi editor namespace — editor metadata, "
                     "not an AI finding",
            ))
    for elem in root.iter():
        tag = _local(elem.tag)
        for attr, val in elem.attrib.items():
            if _local(attr) == "generator":
                check_metadata_value("generator", val,
                                     f"SVG <{tag}> generator attribute",
                                     findings)
        if tag in ("metadata", "rdf", "title", "desc") and elem.text:
            markers = find_ai_markers(elem.text)
            if markers:
                findings.append(Finding(
                    severity="medium", confidence="confirmed",
                    category="ai-metadata", location=f"SVG <{tag}>",
                    evidence=elem.text.strip()[:160],
                    note=f"AI-generator marker(s): {', '.join(markers)}",
                ))
            elif tag == "metadata" and elem.text.strip():
                _xmp_scan(elem.text, "SVG <metadata>", findings)
    return findings


