# ---------------------------------------------------------------------------
# Container detection (magic bytes / zip namelist — never extension)
# ---------------------------------------------------------------------------

def detect_container(source) -> str:
    """Return one of CONTAINERS for a path, bytes, or binary file object."""
    if hasattr(source, "read"):
        head = source.read(_HEAD)
        full = None
    elif isinstance(source, (bytes, bytearray)):
        head = bytes(source[:_HEAD])
        full = bytes(source)
    else:
        with open(os.fspath(source), "rb") as fh:
            head = fh.read(_HEAD)
        full = None

    def _full_bytes():
        if full is not None:
            return full
        if hasattr(source, "read"):
            source.seek(0)
            return source.read()
        with open(os.fspath(source), "rb") as fh:
            return fh.read()

    if head.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if head.startswith(b"\xff\xd8\xff"):
        return "jpeg"
    if head[:4] == b"RIFF" and head[8:12] == b"WEBP":
        return "webp"
    if head.startswith(b"GIF8"):
        return "gif"
    if head[:4] in (b"II*\x00", b"MM\x00*", b"II+\x00", b"MM\x00+"):
        return "tiff"
    if head.startswith(b"%PDF"):
        return "pdf"
    if head.startswith(b"PK\x03\x04"):
        try:
            zf = zipfile.ZipFile(io.BytesIO(_full_bytes()))
            names = set(zf.namelist())
            if "mimetype" in names:
                mt = zf.read("mimetype")[:128].decode("ascii", "replace")
                if mt.startswith("application/vnd.oasis.opendocument"):
                    return "odt"
            if "word/document.xml" in names:
                return "docx"
            if "META-INF/container.xml" in names and any(
                    n.endswith(".opf") for n in names):
                return "epub"
        except (zipfile.BadZipFile, KeyError, OSError):
            pass
        return "unknown-binary"

    if sniff_format(head) == "binary":
        return "unknown-binary"

    text = head.decode("utf-8", "replace")
    stripped = text.lstrip()
    low = stripped[:1024].lower()
    if low.startswith("<?xml") and "<svg" in low or low.startswith("<svg"):
        return "svg"
    if re.match(r"^---[ \t]*\r?\n", stripped):
        return "markdown"
    if low.startswith("<!doctype html") or low.startswith("<html") \
            or "<meta" in text[:1024].lower():
        return "html"
    return "text"


